export function getLocationDistribution(records) {
  const counts = new Map(PROVINCES.map(([name]) => [name, 0]));
  let identifiableRecords = 0;
  records.forEach(record => {
    const location = String(record.location || '');
    const matched = PROVINCES.filter(([, keywords]) => keywords.some(keyword => location.includes(keyword)));
    if (matched.length) identifiableRecords += 1;
    matched.forEach(([name]) => counts.set(name, counts.get(name) + 1));
  });
  return { identifiableRecords, provinces: PROVINCES.map(([name]) => ({ name, value: counts.get(name) })) };
}

export function filterRecordsByProvince(records, province) {
  if (!province) return records;
  const keywords = PROVINCES.find(([name]) => name === province)?.[1];
  return keywords ? records.filter(record => keywords.some(keyword => String(record.location || '').includes(keyword))) : [];
}
